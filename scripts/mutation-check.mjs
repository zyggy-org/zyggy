#!/usr/bin/env node
// The slice's mutation check (spec-driven kit 3.0.0, pack dotnet-shared): the proof that the slice's tests can fail.
// Installed as <project>/scripts/mutation-check.mjs.
//
//   node scripts/mutation-check.mjs --slice <name> --base <commit> [--feature <FeatureName>] [--files <path>...]
//
// 1. The files: the production files the slice changed since --base (git diff and untracked files), under src/ only,
//    without tests, generated code, markup-only .razor files and resources; --files replaces the list.
//    The lines (2.6.5): per file the line ranges the slice added or modified (git diff -U0 against --base); a file that
//    is untracked counts whole. A listed file without a changed line is not mutated.
// 2. Stryker.NET (the local tool dotnet-stryker, pinned in .config/dotnet-tools.json) runs once per production project,
//    on the Microsoft testing platform runner (-t mtp), mutating only those lines, with every test project of
//    CLAUDE.md § Project settings, Pack values **Test projects**; the full JSON and HTML report go to
//    artifacts/mutation/<slice>/ (ignored by git). Each changed range is one --mutate pattern with a Stryker.NET text
//    span, "File.cs{first..last}": Stryker.NET's mutate filter takes the indices of the first and the last character,
//    not line numbers, so each line range is turned into its character span (characterSpans).
// 3. The safety net: only the mutants whose location intersects a changed range count in the score, the printed list and
//    the evidence; the others are counted on one line, "outside the slice: n (not scored)".
// 4. It prints one line, "mutation: score s% (killed k, survived v, no coverage n, timeout t)", the outside line, then
//    each survivor and each mutant without coverage as file:line mutator, and writes the committed evidence
//    _specs/<Feature>/mutation-<slice>.md: the score line, the files and lines mutated and each survivor with its
//    classification (equivalent or accepted, filled in by the build, kept when the check runs again) and one line why.
//
// Exit codes: 0 green; 1 the score is below Pack values **Mutation threshold** (default 80) or a mutant has no coverage;
// 2 a usage or configuration error; 3 dotnet-stryker not available; 4 Stryker.NET failed or wrote no report.
// MUTATION_CHECK_DOTNET names another dotnet executable (a .mjs or .js file runs with node: the kit's own tests).

import { spawnSync, execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DEFAULT_THRESHOLD = 80;
export const TOOL = 'dotnet-stryker';
const NOT_AVAILABLE = `${TOOL} not available: run dotnet tool restore (the tool comes from nuget.org), see README`;
const EXIT = { green: 0, red: 1, usage: 2, tool: 3, stryker: 4 };
const slash = (path) => path.split('\\').join('/');

/** A folder of a test project: Test or Tests, or a name ending in Tests or Test after a dot (App.Tests, App.IntegrationTests). */
const TEST_FOLDER = /^[Tt]ests?$|\.\w*Tests?$|^\w*Tests$/;
const TEST_FILE = /Tests?\.cs$/;
const GENERATED_NAME = /\.(?:g|g\.i|designer|generated)\.cs$|AssemblyInfo\.cs$/i;
const BUILD_FOLDER = /^(?:obj|bin)$/i;
const AUTO_GENERATED = /<auto-generated/i;
/** A Razor file with code of its own: a code or functions block (markup-only Razor has nothing to mutate). */
const RAZOR_CODE = /[@](?:code|functions)\b/;

/**
 * The production files of a list of changed paths (relative to the project, forward slashes), sorted: C# and Razor
 * files under src/, not in a test project or a build folder, not generated (by name or by an auto-generated header), and
 * a .razor file only when it holds a code block. read(path) gives a file's text.
 */
export function productionFiles(paths, read) {
  const kept = new Set();
  for (const path of paths.map(slash)) {
    if (!path.startsWith('src/')) continue;
    const segments = path.split('/');
    const name = segments.at(-1);
    const folders = segments.slice(1, -1);
    if (!/\.(?:cs|razor)$/.test(name)) continue;
    if (folders.some((f) => TEST_FOLDER.test(f) || BUILD_FOLDER.test(f)) || TEST_FILE.test(name) || GENERATED_NAME.test(name)) continue;
    let text = '';
    try {
      text = read(path) ?? '';
    } catch {
      continue; // deleted since the base: nothing to mutate
    }
    if (AUTO_GENERATED.test(text.split(/\r?\n/).slice(0, 5).join('\n'))) continue;
    if (name.endsWith('.razor') && !RAZOR_CODE.test(text)) continue;
    kept.add(path);
  }
  return [...kept].sort();
}

/** The values of CLAUDE.md § Project settings the check reads: the test projects, the threshold, the specs folder. */
export function readSettings(text) {
  const line = (label) => text.split(/\r?\n/).find((l) => l.startsWith(`- **${label}**`)) ?? '';
  const testProjects = [...line('Test projects').matchAll(/`([^`]+\.csproj)`/g)].map((m) => slash(m[1]));
  const threshold = Number(/(\d+(?:\.\d+)?)/.exec(line('Mutation threshold').replace(/^- \*\*[^*]+\*\*/, ''))?.[1] ?? DEFAULT_THRESHOLD);
  const specsDir = (/`([^`]+)`/.exec(line('Specs folder'))?.[1] ?? '_specs').replace(/\/+$/, '');
  return { testProjects, threshold, specsDir };
}

/** The mutants of Stryker.NET JSON reports (mutation-testing-elements), each { file, line, mutator, status }. */
export function reportMutants(reports) {
  const mutants = [];
  for (const { report, root, projectDir } of reports) {
    for (const [path, file] of Object.entries(report.files ?? {})) {
      const absolute = isAbsolute(path) ? path : resolve(projectDir, path);
      const rel = slash(relative(root, absolute));
      for (const m of file.mutants ?? []) {
        const line = m.location?.start?.line ?? 0;
        mutants.push({ file: rel, line, endLine: m.location?.end?.line ?? line, mutator: m.mutatorName ?? m.mutatorname ?? 'mutation', status: m.status });
      }
    }
  }
  return mutants.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
}

/** A path of a diff header: b/<path>, quoted by git when it holds special characters; null for /dev/null. */
function diffPath(raw) {
  let path = raw.trim();
  if (path.startsWith('"') && path.endsWith('"')) path = JSON.parse(path);
  if (path === '/dev/null') return null;
  return path.startsWith('b/') ? path.slice(2) : path;
}

/**
 * The changed line ranges of a `git diff -U0` (2.6.5): per file (the new path), the lines added or modified, as
 * [first, last] pairs in the new file. A hunk that only deletes lines has none; a deleted file has none.
 */
export function changedRanges(diff) {
  const ranges = new Map();
  let file = null;
  let header = false;
  for (const line of String(diff ?? '').split(/\r?\n/)) {
    if (line.startsWith('diff --git ')) {
      file = null;
      header = true;
    } else if (header && line.startsWith('+++ ')) {
      file = diffPath(line.slice(4));
    } else if (line.startsWith('@@ ')) {
      header = false;
      const hunk = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/.exec(line);
      const count = hunk ? Number(hunk[2] ?? 1) : 0;
      if (!file || count === 0) continue;
      const first = Number(hunk[1]);
      if (!ranges.has(file)) ranges.set(file, []);
      ranges.get(file).push([first, first + count - 1]);
    }
  }
  return ranges;
}

/**
 * The character spans of line ranges in a file's text, as Stryker.NET's mutate filter reads them: [start, end] with
 * start the index of a range's first character and end the index just after its last line's last character (line
 * ends excluded); a UTF-8 byte-order mark is not counted (Roslyn leaves it out of the text); CRLF counts two.
 */
export function characterSpans(text, ranges) {
  const body = String(text ?? '').replace(/^﻿/, '');
  const starts = [0];
  for (let i = 0; i < body.length; i += 1) if (body[i] === '\n') starts.push(i + 1);
  const lineEnd = (n) => {
    const next = n < starts.length ? starts[n] - 1 : body.length; // the \n of line n, or the end of the text
    return next > starts[n - 1] && body[next - 1] === '\r' && n < starts.length ? next - 1 : next;
  };
  const spans = [];
  for (const [first, last] of ranges) {
    if (first > starts.length) continue;
    const end = Math.min(last, starts.length);
    spans.push([starts[first - 1], lineEnd(end)]);
  }
  return spans;
}

/** The --mutate patterns of a file (relative to its project): one per changed range, `File.cs{start..end}`; ranges null: the whole file. */
export function mutatePatterns(path, text, ranges) {
  if (ranges === null) return [path];
  return characterSpans(text, ranges).map(([start, end]) => `${path}{${start}..${end}}`);
}

/**
 * The safety net (2.6.5): the mutants whose location (start to end line) intersects a changed range of their file are
 * inside the slice; the rest, a file without ranges included, are outside. rangesByFile maps a file to its ranges, or
 * to null when the whole file counts.
 */
export function sliceMutants(mutants, rangesByFile) {
  const inside = [];
  const outside = [];
  for (const m of mutants) {
    const ranges = rangesByFile.get(m.file);
    const end = Math.max(m.endLine ?? m.line, m.line);
    const hit = ranges === null || (ranges ?? []).some(([first, last]) => m.line <= last && end >= first);
    (hit ? inside : outside).push(m);
  }
  return { inside, outside };
}

export const outsideLine = (n) => `outside the slice: ${n} (not scored)`;

/** The score: killed and timed-out mutants of all with a verdict (killed, timeout, survived, no coverage), in percent. */
export function score(mutants) {
  const count = (status) => mutants.filter((m) => m.status === status).length;
  const counts = { killed: count('Killed'), survived: count('Survived'), noCoverage: count('NoCoverage'), timeout: count('Timeout') };
  const valid = counts.killed + counts.survived + counts.noCoverage + counts.timeout;
  const value = valid === 0 ? null : ((counts.killed + counts.timeout) * 100) / valid;
  return { ...counts, valid, value };
}

export function scoreLine(s) {
  const value = s.value === null ? 'n/a' : `${Number(s.value.toFixed(1))}%`;
  return `mutation: score ${value} (killed ${s.killed}, survived ${s.survived}, no coverage ${s.noCoverage}, timeout ${s.timeout})`;
}

const key = (m) => `${m.file}:${m.line} ${m.mutator}`;
const STATUS = { Survived: 'survived', NoCoverage: 'no coverage' };
const ROW = /^\| `([^`]+)` \| ([^|]+?) \| ([^|]+?) \| (.*?) \|$/;

/** The classifications already written in an evidence file, by mutant: { classification, why }. */
export function classifications(text) {
  const found = new Map();
  for (const line of String(text ?? '').split(/\r?\n/)) {
    const m = ROW.exec(line);
    if (m && !found.has(m[1])) found.set(m[1], { classification: m[3].trim(), why: m[4].trim() });
  }
  return found;
}

/** The committed evidence of a slice: the score line, the files mutated and each survivor with its classification. */
export function evidence({ slice, base, threshold, files, line, mutants, previous, ranges = new Map(), outside = 0 }) {
  const kept = classifications(previous);
  const lines = (f) => {
    const r = ranges.get(f);
    if (r === undefined) return '';
    if (r === null) return ' (whole file, new in the slice)';
    return ` lines ${r.map(([a, b]) => (a === b ? `${a}` : `${a}-${b}`)).join(', ')}`;
  };
  const rows = mutants.filter((m) => m.status in STATUS).map((m) => {
    const { classification, why } = kept.get(key(m)) ?? { classification: 'unclassified', why: '' };
    return `| \`${key(m)}\` | ${STATUS[m.status]} | ${classification} | ${why.replace(/(?<!\\)\|/g, '\\|')} |`;
  });
  return [
    `# Mutation check: ${slice}`,
    '',
    '<!-- Written by scripts/mutation-check.mjs and committed with the slice. For each survivor the build writes the classification',
    "     ('equivalent' only when no test could ever observe the change; else 'accepted', for the reviewer to approve) and one line why;",
    '     the classifications are kept when the check runs again. -->',
    '',
    line,
    outsideLine(outside),
    '',
    `- Base: \`${base.slice(0, 12)}\``,
    `- Threshold: ${threshold}%`,
    `- Report: \`artifacts/mutation/${slice}/\` (not committed)`,
    '',
    '## Files mutated',
    '',
    '<!-- Only the lines the slice added or modified are mutated and scored; a survivor outside them is never a reason to add a test. -->',
    '',
    ...(files.length ? files.map((f) => `- \`${f}\`${lines(f)}`) : ['None: no production file changed since the base.']),
    '',
    '## Survivors',
    '',
    ...(rows.length ? ['| Mutant | Status | Classification | Why |', '|---|---|---|---|', ...rows] : ['None.']),
    '',
  ].join('\n');
}

function parseArgs(argv) {
  const options = { files: null };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--slice' || arg === '--base' || arg === '--feature') options[arg.slice(2)] = argv[++i];
    else if (arg === '--files') {
      options.files = [];
      while (i + 1 < argv.length && !argv[i + 1].startsWith('--')) options.files.push(argv[++i]);
    } else throw new Error(`unknown option ${arg}`);
  }
  if (!options.slice || !/^[\w.-]+$/.test(options.slice)) throw new Error('--slice <name> is required (letters, digits, _ . - only)');
  if (!options.base) throw new Error('--base <commit> is required: the commit the slice started from');
  if (options.feature !== undefined && !/^[\w.-]+$/.test(options.feature)) throw new Error('--feature takes the name of a folder under the specs folder');
  return options;
}

function git(root, args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
}

/** The paths changed since the base: committed, staged, unstaged and untracked, deleted ones left out. */
function changedPaths(root, base) {
  const diff = git(root, ['diff', '--name-only', '--no-renames', '--diff-filter=d', '--relative', base, '--']);
  const untracked = git(root, ['ls-files', '--others', '--exclude-standard']);
  return [...new Set([...diff.split('\n'), ...untracked.split('\n')].map((p) => p.trim()).filter(Boolean))];
}

/** The changed line ranges of the files since the base (2.6.5): from git diff -U0; an untracked file is whole (null). */
function lineRanges(root, base, files) {
  const untracked = new Set(git(root, ['ls-files', '--others', '--exclude-standard', '--', ...files]).split('\n').map((p) => p.trim()).filter(Boolean));
  const tracked = files.filter((f) => !untracked.has(f));
  const diff = tracked.length ? changedRanges(git(root, ['diff', '-U0', '--no-color', '--no-ext-diff', '--no-renames', '--relative', base, '--', ...tracked])) : new Map();
  const ranges = new Map();
  for (const f of files) {
    if (untracked.has(f)) ranges.set(f, null);
    else if (diff.has(f)) ranges.set(f, diff.get(f));
  }
  return ranges;
}

/** The feature whose spec names the current branch, when exactly one does. */
function featureOfBranch(root, specsDir) {
  let branch = '';
  try {
    branch = git(root, ['rev-parse', '--abbrev-ref', 'HEAD']).trim();
  } catch {
    return null;
  }
  const dir = join(root, specsDir);
  if (!branch || branch === 'HEAD' || !existsSync(dir)) return null;
  const named = readdirSync(dir).filter((name) => {
    const spec = join(dir, name, 'spec.md');
    return existsSync(spec) && readFileSync(spec, 'utf8').split(/^## /m).find((s) => s.startsWith('Status'))?.includes(branch);
  });
  return named.length === 1 ? named[0] : null;
}

/** The folder of the nearest .csproj above a file, up to the project root; null without one. */
function projectOf(root, file) {
  for (let dir = dirname(join(root, file)); relative(root, dir) && !relative(root, dir).startsWith('..'); dir = dirname(dir)) {
    const csproj = readdirSync(dir).find((n) => n.endsWith('.csproj'));
    if (csproj) return { dir, csproj };
  }
  return null;
}

function dotnet(args, cwd) {
  const command = process.env.MUTATION_CHECK_DOTNET || 'dotnet';
  const [exe, all] = /\.m?js$/.test(command) ? [process.execPath, [command, ...args]] : [command, args];
  const run = spawnSync(exe, all, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  return { status: run.error ? -1 : run.status, output: `${run.stdout ?? ''}${run.stderr ?? ''}${run.error ? run.error.message : ''}` };
}

function findReport(dir) {
  if (!existsSync(dir)) return null;
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      const found = findReport(path);
      if (found) return found;
    } else if (name === 'mutation-report.json') return path;
  }
  return null;
}

const tail = (text, n = 20) => text.trimEnd().split(/\r?\n/).slice(-n).join('\n');

function fail(code, message) {
  console.error(message);
  process.exit(code);
}

function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  let options;
  try {
    options = parseArgs(process.argv.slice(2));
  } catch (error) {
    fail(EXIT.usage, `mutation-check: ${error.message}\nUsage: node scripts/mutation-check.mjs --slice <name> --base <commit> [--feature <FeatureName>] [--files <path>...]`);
  }
  const claude = join(root, 'CLAUDE.md');
  const settings = readSettings(existsSync(claude) ? readFileSync(claude, 'utf8') : '');
  try {
    git(root, ['rev-parse', '--verify', '-q', `${options.base}^{commit}`]);
  } catch {
    fail(EXIT.usage, `mutation-check: --base ${options.base} is not a commit of this repository`);
  }
  const feature = options.feature ?? featureOfBranch(root, settings.specsDir);
  if (!feature || !existsSync(join(root, settings.specsDir, feature, 'spec.md'))) {
    fail(EXIT.usage, `mutation-check: name the feature whose spec the slice builds: --feature <FeatureName> (${settings.specsDir}/<FeatureName>/spec.md must exist)`);
  }
  const evidenceFile = join(root, settings.specsDir, feature, `mutation-${options.slice}.md`);
  const previous = existsSync(evidenceFile) ? readFileSync(evidenceFile, 'utf8') : '';
  const read = (path) => readFileSync(join(root, path), 'utf8');
  const candidates = productionFiles(options.files ?? changedPaths(root, options.base), read);
  const ranges = lineRanges(root, options.base, candidates);
  const files = candidates.filter((f) => ranges.has(f));
  const write = (line, mutants, outside = 0) => {
    writeFileSync(evidenceFile, evidence({ slice: options.slice, base: options.base, threshold: settings.threshold, files, line, mutants, previous, ranges, outside }));
    console.log(`Evidence: ${slash(relative(root, evidenceFile))} (commit it with the slice; classify each survivor there).`);
  };

  if (files.length === 0) {
    const line = 'mutation: no production file or line changed since the base; nothing to mutate';
    console.log(line);
    write(line, []);
    process.exit(EXIT.green);
  }
  if (settings.testProjects.length === 0) {
    fail(EXIT.usage, 'mutation-check: no test project in CLAUDE.md § Project settings, Pack values **Test projects** (each .csproj in backticks)');
  }
  const toolsFile = join(root, '.config/dotnet-tools.json');
  let listed = false;
  try {
    listed = Boolean(JSON.parse(readFileSync(toolsFile, 'utf8')).tools?.[TOOL]);
  } catch {
    listed = false;
  }
  if (!listed) fail(EXIT.tool, `${NOT_AVAILABLE} (it is not in .config/dotnet-tools.json; the kit's installer pins it there)`);
  const restore = dotnet(['tool', 'restore'], root);
  if (restore.status !== 0) fail(EXIT.tool, `${NOT_AVAILABLE}\n${tail(restore.output)}`);

  const groups = new Map();
  for (const file of files) {
    const owner = projectOf(root, file);
    if (!owner) fail(EXIT.usage, `mutation-check: no .csproj above ${file}`);
    const id = join(owner.dir, owner.csproj);
    if (!groups.has(id)) groups.set(id, { ...owner, files: [] });
    groups.get(id).files.push(file);
  }
  const out = join(root, 'artifacts', 'mutation', options.slice);
  rmSync(out, { recursive: true, force: true });
  const reports = [];
  for (const { dir, csproj, files: mutate } of groups.values()) {
    const output = join(out, basename(csproj, '.csproj'));
    mkdirSync(output, { recursive: true });
    const args = ['tool', 'run', TOOL, '-t', 'mtp', '--project', csproj,
      ...settings.testProjects.flatMap((p) => ['--test-project', slash(relative(dir, join(root, p)))]),
      ...mutate.flatMap((f) => mutatePatterns(slash(relative(dir, join(root, f))), read(f), ranges.get(f)).flatMap((p) => ['--mutate', p])),
      '--reporter', 'json', '--reporter', 'html', '--output', output];
    const run = dotnet(args, dir);
    writeFileSync(join(output, 'stryker-output.txt'), run.output);
    const reportFile = findReport(output);
    if (run.status !== 0 || !reportFile) {
      fail(EXIT.stryker, `mutation-check: Stryker.NET failed for ${csproj} (exit ${run.status}${reportFile ? '' : ', no report'}); its output is in ${slash(relative(root, output))}/stryker-output.txt\n${tail(run.output)}`);
    }
    reports.push({ report: JSON.parse(readFileSync(reportFile, 'utf8')), root, projectDir: dir });
  }

  const { inside: mutants, outside } = sliceMutants(reportMutants(reports), ranges);
  const s = score(mutants);
  const line = scoreLine(s);
  console.log(line);
  console.log(outsideLine(outside.length));
  for (const m of mutants.filter((x) => x.status in STATUS)) console.log(`  ${key(m)} (${STATUS[m.status]})`);
  console.log(`Report: ${slash(relative(root, out))}/ (JSON and HTML)`);
  write(line, mutants, outside.length);
  const reasons = [];
  if (s.value !== null && s.value < settings.threshold) reasons.push(`the score is below the threshold ${settings.threshold}%`);
  if (s.noCoverage > 0) reasons.push(`${s.noCoverage} mutant${s.noCoverage === 1 ? ' has' : 's have'} no coverage`);
  if (reasons.length) {
    console.log(`Mutation check red: ${reasons.join('; ')}. Add or strengthen a test (seen red first); never weaken code or delete a line to raise the score.`);
    process.exit(EXIT.red);
  }
  console.log('Mutation check green.');
  process.exit(EXIT.green);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) main();
